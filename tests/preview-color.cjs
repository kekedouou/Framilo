'use strict';
const assert=require('assert');
const {previewColor,previewRgbFilter,ffmpegArgs,COLOR_VERSION}=require('../plugin/media.cjs')._test;
const {oracle,differences}=require('../prototypes/preview-quality/color-check.cjs');
assert.deepStrictEqual([...oracle(Buffer.from([16,128,128]),1,1,'bt709','tv')],[0,0,0]);
assert.deepStrictEqual([...oracle(Buffer.from([235,128,128]),1,1,'bt709','tv')],[255,255,255]);
assert.deepStrictEqual([...oracle(Buffer.from([81,90,240]),1,1,'bt601','tv')],[254,0,0]);
assert.deepStrictEqual([...oracle(Buffer.from([128,128,128]),1,1,'bt709','pc')],[128,128,128]);
assert(differences(oracle(Buffer.from([81,90,240]),1,1,'bt601','tv'),oracle(Buffer.from([81,90,240]),1,1,'bt709','tv')).max>20);
assert.strictEqual(previewColor({}).matrix,'bt709');
assert.strictEqual(previewColor({color_space:'unknown'}).fallback,true);
assert.strictEqual(previewColor({color_primaries:'smpte170m'}).matrix,'bt601');
assert.strictEqual(previewColor({color_primaries:'smpte170m',color_transfer:'bt709'}).matrix,'bt709');
assert.strictEqual(previewColor({color_space:'bt470bg',color_transfer:'bt709'}).matrix,'bt601');
for(const matrix of ['bt470bg','smpte170m'])assert.strictEqual(previewColor({color_space:matrix}).matrix,'bt601');
assert.strictEqual(previewColor({color_space:'bt709',color_range:'pc'}).range,'pc');
assert.strictEqual(previewColor({color_space:'bt709',color_range:'tv'}).range,'tv');
assert.strictEqual(previewColor({color_space:'bt2020nc',color_primaries:'bt2020',color_transfer:'smpte2084'}).matrix,'bt2020');
assert.match(previewColor({color_transfer:'arib-std-b67'}).scope,/not color-validated/);
assert.strictEqual(previewColor({color_space:'unrecognized'}).matrix,'auto');
assert.strictEqual(previewColor({color_space:'bt709'}).fallback,false);
const args=ffmpegArgs('virtual source.mp4',true,'h264',{color_space:'bt709',color_range:'tv'}),vf=args[args.indexOf('-vf')+1];
assert(vf.includes(previewRgbFilter({color_space:'bt709',color_range:'tv'},1280,720)));
assert(vf.indexOf('format=rgb24')<vf.indexOf('out_color_matrix=bt601'));
assert(vf.includes('full_chroma_int'));assert(vf.endsWith('format=yuvj420p'));
assert(args.includes('pipe:3'));assert(args.includes('-copyts'));assert.match(COLOR_VERSION,/^[a-z0-9-]+$/);
console.log('preview color: matrix/range defaults, declared metadata, RGB boundary, JPEG601 and unchanged audio/PTS checked; no real media/GUI');
